-- إضافة عمود grades (JSONB) لجدول hadiths لفصل درجة/حكم الحديث عن
-- متنه، بلا ترجيح بين علماء متعددين لنفس الحديث. بنية القيمة:
-- [{"scholar": "الألباني"|null, "grade_en": "Sahih"|null, "grade_ar": "صحيح"}]
-- - grade_en: النص الإنجليزي الحرفي كما ورد بمصدر fawazahmed0/hadith-api
--   (بخاري/مسلم/ترمذي/أبوداود/نسائي/ابن ماجه)، أو null لصفوف HadeethEnc.
-- - grade_ar: ترجمة ميكانيكية (قاموس ثابت لمفردات المصطلح الحديثي، لا
--   حكم جديد) لبخاري/مسلم/الأربعة الباقية، أو نسخ حرفي من عمود grade
--   النصي الموجود مسبقاً لصفوف HadeethEnc.
-- - scholar: اسم العالِم المحكِّم (8 علماء معروفون بالمصدر)، أو null
--   لصفوف HadeethEnc (لا عالِم فردي مذكور بمصدرها).
-- بخاري ومسلم: العمود يبقى NULL عمداً (بقرار محمد الصريح 2026-09-09)
-- - لا نص "متفق على صحته" يُضاف لأنه غير مذكور حرفياً بصف الحديث نفسه
-- بالمصدر، رغم كونه حقيقة علمية معروفة عن الكتابين ككل.

ALTER TABLE public.hadiths ADD COLUMN IF NOT EXISTS grades JSONB;

COMMENT ON COLUMN public.hadiths.grades IS
  'مصفوفة درجات الحديث من عالِم واحد أو أكثر (JSONB)، بلا ترجيح بيننا بين الآراء. NULL لبخاري/مسلم عمداً (لا درجة فردية بالمصدر أصلاً - إجماع على الصحة).';
