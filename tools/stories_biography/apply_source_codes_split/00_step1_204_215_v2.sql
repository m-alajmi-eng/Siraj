-- نسخة معدَّلة v2: كل صف بمعاملة مستقلة تماماً (لا يؤثر أحدهما على الآخر)،
-- ومطابقة WHERE على بداية النص فقط (LIKE على أول ~15 حرفاً، لا النص الكامل) +
-- id + source_codes IS NULL - يتحقق فعلياً من المحتوى بلا هشاشة أمام فروقات
-- الأسطر وسط نص طويل. SELECT تحقق قبل كل UPDATE كما طُلب.

-- ============================================================
-- id=204
-- ============================================================

-- تحقق قبل التحديث - راجع النتيجة، يجب أن تظهر البادئة القديمة بالقوس
SELECT id, source_codes, left(content_ar, 60) AS content_preview
FROM public.stories WHERE id = 204;

BEGIN;

UPDATE public.stories
SET source_codes = 'ب د ع',
    content_ar = 'عمرو بن قيس بن زيد بن سواد بن مالك بن غنم الأنصاري النجاري يكنى أبا عمرو وأبا الحكم شهد بدرا في قول أبي معشر والواقدي وعبد الله بن محمد بن عمارة ولا خلاف بينهم أنه قتل يوم أحد شهيدا أنبأنا عبيد الله بن أحمد بإسناده عن يونس عن ابن إسحاق فيمن قتل يوم أحد من بني النجار ثم من بني سواد بن مالك بن

غنم بن مالك بن النجار عمرو بن قيس وابنه قيس وكذلك نسبه ابن الكلبي وجعله بدريا يقال إنه قتله نوفل بن معاوية الديلي واختلف في شهود أبيه قيس بدرا كالاختلاف في ابنه أخرجه الثلاثة إلا أن أبا نعيم قال عمرو بن قيس بن سواد فأسقط زيدا وأما ابن منده فقال عمرو بن قيس النجاري والله أعلم'
WHERE id = 204
  AND content_ar LIKE '(ب د ع عمرو)%'
  AND source_codes IS NULL;

COMMIT;

-- تحقق بعد التحديث - يجب أن يظهر source_codes='ب د ع' والمحتوى بلا قوس
SELECT id, source_codes, left(content_ar, 60) AS content_preview
FROM public.stories WHERE id = 204;

